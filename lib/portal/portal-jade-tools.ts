// lib/portal/portal-jade-tools.ts — Release 6.5: Portal-safe Jade read tools
// userId NEVER appears in any tool schema exposed to the model.
// All ownership verified server-side via PortalToolContext.
// NEVER returns: passport numbers, supplier costs, margins, rateKeys, or admin data.

import prisma from '@/lib/db'
import { getCustomerBookingState, getCustomerBookingStateLabel, getCustomerBookingStateDescription } from './booking-states'
import { getPassportExpiryStatus } from './traveller-dto'
import { deriveCustomerActions } from './customer-actions'

// ─── Tool context ─────────────────────────────────────────────────────────────

export interface PortalToolContext {
  userId: string  // from authenticated session — NEVER from model input
}

// ─── Tool schemas (what the model sees — no userId exposed) ───────────────────

